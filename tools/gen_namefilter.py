#!/usr/bin/env python3
"""Generates the nickname filter from ONE word list, so the app (js/namefilter.js) and the
server (the name_ok() function inside supabase/schema.sql) always agree.
Edit the lists below, then run:  python3 tools/gen_namefilter.py
"""
import re, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Blocked anywhere inside a name (after un-leeting: sh1t, $hit, s.h.i.t and shiiit are all caught)
STRONG = """fuck fvck phuck fuking fucking motherfuck shit shyt bullshit bitch biatch cunt whore slut bastard asshole arsehole
dickhead cocksucker pussy penis vagina dildo blowjob handjob cumshot jizz wank wanker twat nigger nigga faggot retard spastic
tranny chink rapist porn pornhub hentai neonazi hitler incest pedo paedo molest childporn killyourself
admin moderator""".split()
# Reserved for the developer: the SERVER refuses them (an account that already holds the name may keep it, see register_player),
# but the app lets you type them so the developer can use their own name.
RESERVED = """nyxapse shadowed""".split()
# Blocked only as the WHOLE name or as a whole word in it (short words that appear inside innocent names)
EXACT = """ass arse sex cum tit tits anal anus fag fags coon paki nazi nazis kkk kys xxx rape rapes raped nsfw dick cock boob boobs
hoe thot milf orgy cuck spic kike loli shota mod mods staff official support owner dev system root
fck fuk sht btch cnt dck""".split()
# Harmless words that contain a blocked word (removed before checking)
ALLOW = """scunthorpe shiitake shitake hancock peacock cockpit cocktail woodcock babcock cockney swank swanky wankel snigger
torpedo pedometer retardant badminton therapist therapists""".split()

MAP_FROM, MAP_TO = "013457$@!+", "oieastsait"

def js():
    q = lambda a: ",".join("'%s'" % w for w in a)
    return """/* namefilter.js - GENERATED by tools/gen_namefilter.py. Do not edit by hand: edit the word lists in the tool and run it again.
   Checks a nickname the same way the server does (supabase/schema.sql, name_ok). English words only. */
const NXName = (() => {
 const STRONG = [%s], EXACT = [%s], ALLOW = [%s];
 const MAP = {'0': 'o', '1': 'i', '3': 'e', '4': 'a', '5': 's', '7': 't', '$': 's', '@': 'a', '!': 'i', '+': 't'};
 const collapse = s => s.replace(/(.)\\1+/g, '$1');
 const letters = s => s.replace(/[^a-z]/g, '');
 const unleet = s => s.replace(/[0134578$@!+]/g, c => MAP[c] || c);
 function check(raw) {
  const s = String(raw || '').toLowerCase();
  if (s.replace(/[^0-9]/g, '').length >= 7 || /(https?|www|\\.com|\\.net|\\.org|\\.io|@)/.test(s)) return {ok: false, reason: 'personal'};
  const flat = letters(unleet(s));
  let flat2 = flat; ALLOW.forEach(w => { flat2 = flat2.split(w).join(''); });
  if (STRONG.some(w => flat2.includes(w))) return {ok: false, reason: 'word'};
  for (let i = 1; i < s.length - 1; i++) {   // a symbol standing in for a missing vowel: sh.t, f*ck
   if (/[^a-z0-9]/.test(s[i]) && /[a-z0-9]/.test(s[i - 1]) && /[a-z0-9]/.test(s[i + 1])) {
    for (const v of 'aeiou') { let fv = letters(unleet(s.slice(0, i) + v + s.slice(i + 1))); ALLOW.forEach(w => { fv = fv.split(w).join(''); }); if (STRONG.some(w => fv.includes(w))) return {ok: false, reason: 'word'}; }
   }
  }
  const col = collapse(flat);
  if (col !== flat) {                      // stretched letters like fuuuck or sshhiitt
   let col2 = col; ALLOW.forEach(w => { col2 = col2.split(collapse(w)).join(''); });
   if (STRONG.some(w => { const c = collapse(w); return c.length >= 4 && col2.includes(c); })) return {ok: false, reason: 'word'};
  }
  if (EXACT.includes(flat) || EXACT.includes(letters(s))) return {ok: false, reason: 'word'};
  for (const t of s.split(/[^a-z0-9]+/)) {
   if (!t) continue;
   if (EXACT.includes(letters(unleet(t))) || EXACT.includes(t.replace(/[0-9]+$/, ''))) return {ok: false, reason: 'word'};
  }
  return {ok: true};
 }
 const message = r => r.reason === 'personal' ? 'Please do not put contact details, links or long numbers in your name.' : 'That name is not allowed. Please choose another one.';
 return {check, message, STRONG, EXACT, ALLOW};
})();
window.NXName = NXName;
""" % (q(STRONG), q(EXACT), q(ALLOW))

def sql():
    arr = lambda a: "array[%s]" % ",".join("'%s'" % w for w in a)
    return """-- >>> NAMEFILTER (generated by tools/gen_namefilter.py - edit the word lists there, not here)
create or replace function public.name_ok(p text)
returns boolean language plpgsql immutable set search_path = public as $$
declare
  strong text[] := %s;
  exact  text[] := %s;
  allow  text[] := %s;
  s text := lower(coalesce(p, ''));
  flat text; flat2 text; col text; col2 text; w text; wc text; v_tok text; i int; vv text; fv text;
begin
  if length(regexp_replace(s, '[^0-9]', '', 'g')) >= 7 then return false; end if;
  if s ~ '(https?|www|\\.com|\\.net|\\.org|\\.io|@)' then return false; end if;
  flat := regexp_replace(translate(s, '%s', '%s'), '[^a-z]', '', 'g');
  flat2 := flat;
  foreach w in array allow loop flat2 := replace(flat2, w, ''); end loop;
  foreach w in array strong loop
    if position(w in flat2) > 0 then return false; end if;
  end loop;
  for i in 2 .. length(s) - 1 loop   -- a symbol standing in for a missing vowel: sh.t, f*ck
    if substr(s, i, 1) ~ '[^a-z0-9]' and substr(s, i - 1, 1) ~ '[a-z0-9]' and substr(s, i + 1, 1) ~ '[a-z0-9]' then
      foreach vv in array array['a','e','i','o','u'] loop
        fv := regexp_replace(translate(substr(s, 1, i - 1) || vv || substr(s, i + 1), '%s', '%s'), '[^a-z]', '', 'g');
        foreach w in array allow loop fv := replace(fv, w, ''); end loop;
        foreach w in array strong loop
          if position(w in fv) > 0 then return false; end if;
        end loop;
      end loop;
    end if;
  end loop;
  col := regexp_replace(flat, '(.)\\1+', '\\1', 'g');
  if col <> flat then
    col2 := col;
    foreach w in array allow loop col2 := replace(col2, regexp_replace(w, '(.)\\1+', '\\1', 'g'), ''); end loop;
    foreach w in array strong loop
      wc := regexp_replace(w, '(.)\\1+', '\\1', 'g');
      if length(wc) >= 4 and position(wc in col2) > 0 then return false; end if;
    end loop;
  end if;
  if flat = any(exact) or regexp_replace(s, '[^a-z]', '', 'g') = any(exact) then return false; end if;
  foreach v_tok in array regexp_split_to_array(s, '[^a-z0-9]+') loop
    if v_tok = '' then continue; end if;
    if regexp_replace(translate(v_tok, '%s', '%s'), '[^a-z]', '', 'g') = any(exact)
       or regexp_replace(v_tok, '[0-9]+$', '') = any(exact) then
      return false;
    end if;
  end loop;
  return true;
end $$;
revoke all on function public.name_ok(text) from public, anon, authenticated;
-- <<< NAMEFILTER
""" % (arr(STRONG + RESERVED), arr(EXACT), arr(ALLOW), MAP_FROM, MAP_TO, MAP_FROM, MAP_TO, "013457", "oieast")

open(os.path.join(ROOT, 'js/namefilter.js'), 'w', encoding='utf-8').write(js())
p = os.path.join(ROOT, 'supabase/schema.sql'); s = open(p, encoding='utf-8').read()
block = sql()
if '-- >>> NAMEFILTER' in s:
    s = re.sub(r'-- >>> NAMEFILTER.*?-- <<< NAMEFILTER\n', lambda m: block, s, flags=re.S)
else:
    marker = '-- ---------- join the leaderboard ----------'
    assert marker in s
    s = s.replace(marker, block + '\n' + marker, 1)
open(p, 'w', encoding='utf-8').write(s)
print('name filter generated:', len(STRONG), 'strong,', len(EXACT), 'exact,', len(ALLOW), 'allowed')
